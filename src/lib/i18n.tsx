const DICT: Record<Lang, Record<MsgKey, string>> = { en: EN, zh: ZH };

type Vars = Record<string, string | number>;
function interpolate(s: string, vars?: Vars): string {
  // Guard against a missing string (a key absent from both tables, e.g. a
  // runtime-cast key) so a lookup miss degrades to "" instead of throwing.
  if (s == null) return "";
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? "")) : s;
}

interface I18n {
  lang: Lang;
  t: (key: MsgKey, vars?: Vars) => string;
}

const I18nCtx = createContext<I18n>({
  lang: "en",
  t: (key) => EN[key],
});

export function I18nProvider({
  lang,
  children,
}: {
  lang: Lang;
  children: ReactNode;
}) {
  const table = DICT[lang] ?? EN;
  const t = (key: MsgKey, vars?: Vars) => interpolate(table[key] ?? EN[key], vars);
  return <I18nCtx.Provider value={{ lang, t }}>{children}</I18nCtx.Provider>;
}

export function useT(): I18n {
  return useContext(I18nCtx);
}

/** Translate outside React (e.g. in error helpers, async toasts, OS
 *  notifications). Reads the persisted language synchronously. */
export function tStatic(key: MsgKey, vars?: Vars): string {
  const table = DICT[readLang()] ?? EN;
  return interpolate(table[key] ?? EN[key], vars);
}

/** A short, localized "x ago" for a past timestamp (ms epoch). Used by the
 *  conversation list. Pass the same `t` the component already holds so it
 *  follows the live language without re-reading storage. */
export function relativeTime(t: (key: MsgKey, vars?: Vars) => string, ts: number, now = Date.now()): string {
  const sec = Math.max(0, Math.floor((now - ts) / 1000));
  if (sec < 60) return t("agent.time.now");
  const min = Math.floor(sec / 60);
  if (min < 60) return t("agent.time.minutes", { n: min });
  const hr = Math.floor(min / 60);
  if (hr < 24) return t("agent.time.hours", { n: hr });
  const day = Math.floor(hr / 24);
  return t("agent.time.days", { n: day });
}

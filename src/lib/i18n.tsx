// Ported from the mobile wallet (exfer-walletd-mobile/src/lib/i18n.tsx). The
// key set grows as screens are translated; EN is the source of truth and ZH
// must cover every EN key (enforced by `ZH: Record<MsgKey, string>` — a missing
// translation is a compile error).


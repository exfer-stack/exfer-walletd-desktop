export type Lang = "en" | "zh";
export const LANGS: { key: Lang; label: string }[] = [
  { key: "en", label: "EN" },
  { key: "zh", label: "中文" },
];

// Follows the desktop localStorage convention (labels/hidden/history are all
// `exfer-walletd-desktop-*-v1`). Default English; no device-locale detection.
const LS_KEY = "exfer-walletd-desktop-lang-v1";
export function readLang(): Lang {
  try {
    return localStorage.getItem(LS_KEY) === "zh" ? "zh" : "en";
  } catch {
    return "en";
  }
}
export function persistLang(l: Lang) {
  try {
    localStorage.setItem(LS_KEY, l);
  } catch {
    /* ignore */
  }
}

